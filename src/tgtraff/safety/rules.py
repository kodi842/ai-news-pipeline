# И текст, и словарь приводятся к «е»: правило, написанное через «ё»
# («ребёнок», «счёты»), иначе никогда не совпадёт с нормализованным текстом.
_COMPILED = tuple((cat, verdict, re.compile(pattern.replace("ё", "е"), re.I | re.U))
                  for cat, verdict, pattern in _RULES)


def check_text(text: str | None) -> RuleVerdict:
    """Вердикт словаря по тексту (обычно — по готовому драфту)."""
    body = (text or "").lower().replace("ё", "е").replace(" ", " ")
    if not body.strip():
        return RuleVerdict(SAFE)

    hits: list[SafetyHit] = []
    for category, verdict, pattern in _COMPILED:
        m = pattern.search(body)
        if m:
            hits.append(SafetyHit(category=category, verdict=verdict, marker=m.group(0)[:60]))
    if not hits:
        return RuleVerdict(SAFE)
    return RuleVerdict(worst(*(h.verdict for h in hits)), hits)
