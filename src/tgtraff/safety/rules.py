"""Стоп-словарь safety-фильтра (спека §6).

Первый из двух контуров: то, что не должно зависеть от настроения модели.
Словарь намеренно узкий и злой — он ловит формулировки, а не темы, потому что
темы у ЧП-канала как раз тяжёлые. Пост «водитель погиб на месте» обязан
остаться публикуемым: иначе это не канал происшествий.

Вердикты: `safe` / `manual_only` / `reject` (спека). В фазе 4 автопубликации
нет ни при каком вердикте — `safe` означает «модератору можно не вчитываться».
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field

SAFE, MANUAL_ONLY, REJECT = "safe", "manual_only", "reject"
_ORDER = {SAFE: 0, MANUAL_ONLY: 1, REJECT: 2}


def worst(*verdicts: str) -> str:
    return max((v for v in verdicts if v in _ORDER), key=lambda v: _ORDER[v], default=SAFE)


@dataclass(frozen=True)
class SafetyHit:
    category: str
    verdict: str
    marker: str


@dataclass(frozen=True)
class RuleVerdict:
    verdict: str
    hits: list[SafetyHit] = field(default_factory=list)

    @property
    def categories(self) -> list[str]:
        out: list[str] = []
        for h in self.hits:
            if h.category not in out:
                out.append(h.category)
        return out

    @property
    def markers(self) -> list[str]:
        return [h.marker for h in self.hits]


# Каждое правило — (категория, вердикт, регулярка). Регулярки пишутся по
# основам слов: «беспилотник», «беспилотная», «БПЛА» — одно и то же явление.
