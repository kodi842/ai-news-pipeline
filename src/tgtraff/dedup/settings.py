"""Параметры дедупа (config/settings.yaml → блок `dedup`).

Порог и окно — параметры конфига по спеке §3: «cosine > порога (калибруется,
старт 0.85) в окне 48 часов». Остальное — предохранители, найденные на живой
ленте при калибровке (см. PROGRESS, фаза 3).
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class DedupSettings:
    enabled: bool = True

    # ---- модель эмбеддингов: локальная, без внешних API (спека, фаза 3) ----
    model: str = "sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2"
    model_dir: str = "data/models"      # кэш весов рядом с проектом, не в ~/.cache
    device: str = "cpu"
    batch_size: int = 32
    # Модели семейства e5 требуют префикса («query: …»); у MiniLM он пустой.
    text_prefix: str = ""
    # false — работать строго офлайн (веса уже скачаны). На VPS так и надо.
    allow_download: bool = True

    # ---- уровень 2: семантика ----
    threshold: float = 0.85             # cosine-порог склейки
    window_hours: int = 48              # окно сравнения
    # Присоединение проверяется не только по ближайшему посту, но и по кластеру
    # целиком: иначе цепочка A~B~C утаскивает в один кластер несвязанные новости.
    centroid_margin: float = 0.05
    min_chars_for_semantic: int = 40    # короткий текст семантике не доверяем
    # Регулярные рубрики («Доброе утро», «Погода на N сентября», «Спокойной ночи»)
    # у одного источника отличаются только датой и склеиваются на любом пороге.
    # Признак рубрики — тот же источник и разрыв почти ровно в сутки (или двое).
    same_source_daily_guard: bool = True
    daily_gap_tolerance_min: int = 90
    # Сводки полиции и пресс-релизы пишутся по общему шаблону: модель честно даёт
    # им 0.87, хотя речь о разных людях и городах. Требуем хотя бы одно общее имя
    # собственное — но только в середине шкалы: почти дословный текст (выше
    # entity_guard_max_sim) склеиваем и без совпавших имён.
    # Семантика внутри одного источника выключена: у каналов есть рубрики
    # («Момент ДТП на …», «Погода на …», «#Вакансия …»), которые модель считает
    # одним текстом. Ценность кластера — в РАЗНЫХ источниках; точный хэш и
    # картинка внутри источника продолжают работать.
    same_source_semantic: bool = False
    # Повторяющиеся объявления: текст, приходивший в городе столько раз, —
    # шаблон события («введён режим БПЛА»), а не уникальная новость. По нему
    # склеиваем только внутри эпизода.
    template_min_repeats: int = 3
    template_max_gap_hours: int = 6
    entity_guard: bool = True
    entity_guard_min: int = 3
    entity_guard_max_sim: float = 0.95

    # ---- уровень 1: картинки ----
    phash_max_distance: int = 6         # 64 бита; 0-6 — та же картинка
    # Хэш, встреченный у стольких постов одного источника, — шаблон (шапка,
    # логотип, заставка рубрики), а не фактура: для склейки не используется.
    phash_boilerplate_min: int = 3
    # Склейка по картинке требует, чтобы тексты хотя бы не противоречили друг другу.
    phash_text_floor: float = 0.45

    # ---- работа процесса ----
    poll_seconds: int = 60              # шаг фонового прохода
    batch_limit: int = 300              # сколько постов берём за проход
    # Пост без текста с ещё не скачанным медиа ждёт: без картинки и текста
    # кластеризовать его нечем. Ждём не дольше этого срока.
    defer_minutes: int = 15

    @property
    def centroid_threshold(self) -> float:
        return max(0.0, self.threshold - self.centroid_margin)
